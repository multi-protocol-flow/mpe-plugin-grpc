type Params = Record<string, string | number>;

/**
 * Resolve a dotted path in the active locale dictionary and interpolate
 * `{name}` placeholders. Missing keys fall back to the path itself.
 */
export function t(path: string, params?: Params): string {
  const dict = currentLocale === 'zh-CN' ? zh : en;
  const value = path.split('.').reduce<unknown>((acc, key) => {
    if (acc && typeof acc === 'object') {
      return (acc as Dict)[key];
    }
    return undefined;
  }, dict);
  if (typeof value !== 'string') return path;
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  );
}
